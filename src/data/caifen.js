/** 铺作竖向步进:每出一跳升一足材(21分),栌斗自身 20 分 [法] */
export const PUZUO_RISE = { luDouH: PART.luDou.h, perTiao: 21 };

/**
 * 昂跳的竖向步进(分°)[法/派生]——第13轮裁决二。
 *
 * 下昂是**斜置**构件:它一边出挑一边下行,故一个昂跳抬升的高度**小于**华栱跳的一足材。
 * 这正是下昂存在的结构目的之一 —— 出挑更远、抬升更少。此前文法对昂跳也按足材堆,
 * 含昂各层(副阶/L1/L2)因此系统性偏高,残差量级与「双昂 × 每昂省 0.1~0.15 m」吻合。
 *
 *   昂跳步进 = 足材 − 昂斜率 × 跳距 = 21 − 0.35×30 = 10.5 分
 *   k_ang    = 10.5 / 21 = 0.500
 *
 * ★ 诚实标注:k_ang 恰为 0.5 是 angSlope=0.35 [估] 与「一跳30分/足材21分」相乘的巧合
 *   (0.35×30 = 10.5 = 半足材),不是《法式》给的整数关系。angSlope 由此从「装饰性倾角」
 *   变成**承担结构后果**的量:它现在直接决定含昂铺作的总高,任何调整都会改变檐口关系。
 *   其数值来源仍待图版实测升级。
 */
export const ANG_RISE = PUZUO_RISE.perTiao - PART.angSlope * PART.tiao;
export const K_ANG = ANG_RISE / PUZUO_RISE.perTiao;

/** 暗栔:柱头枋道与道之间的填木,厚度即栔(6分)[法]卷四「材」 */
export const ANZHI_H = ZHI;

/** 由 config 计算一朵铺作的总高(米)——竖向堆叠与暗层柱高反解的共同依据 */
export function bracketHeight(cfg) {
  const ang = cfg.ang ?? 0;
  const hua = cfg.tiao - ang;
  return fen(PUZUO_RISE.luDouH + hua * PUZUO_RISE.perTiao + ang * ANG_RISE);
}
/** 由 config 计算总出跳(米):每跳 30 分 [图]版21 总出跳209cm÷4跳自洽 */
export function bracketReach(cfg) {
  return fen(cfg.tiao * PART.tiao);
}
